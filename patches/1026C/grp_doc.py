NUM='一二三四五六七八九十'
def cn(n):
  if n<=10:return NUM[n-1] if n<10 else '十'
  return '十'+NUM[n-11] if n<20 else '二十'+(NUM[n-21] if n>20 else '')
def html():
  h=[];k=0
  for ch,arts in CH:
    h.append('<h4 class="ch">'+ch+'</h4>')
    for t,ps in arts:
      k+=1
      s='<div class="art"><span class="t">第 %d 條　%s</span>'%(k,t)
      for p in ps:
        if isinstance(p,tuple):
          s+='<ol class="kuan">'+''.join('<li><b>%s、</b>%s</li>'%(cn(i+1),x) for i,x in enumerate(p[1]))+'</ol>'
        elif p.startswith('<table'):s+=p
        else:s+='<p>'+p+'</p>'
      h.append(s+'</div>')
  return ''.join(h),k
