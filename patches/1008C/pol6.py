ART = re.compile(r'<div class="art"><span class="t">第 (\d+) 條　(.*?)</span>(.*?)</div>(?=<div class="art"><span class="t">|$)', re.S)
def parse(h):
    parts = re.split(r'<h4 class="ch">(.*?)</h4>', h)
    assert parts[0] == '', parts[0][:40]
    chs = []
    for i in range(1, len(parts), 2):
        name = parts[i].split('　', 1)[1]
        seg = parts[i + 1]
        arts = [dict(no=int(m.group(1)), t=m.group(2), b=m.group(3)) for m in ART.finditer(seg)]
        assert ''.join('<div class="art"><span class="t">第 %d 條　%s</span>%s</div>' % (a['no'], a['t'], a['b']) for a in arts) == seg, name
        chs.append(dict(name=name, arts=arts))
    return chs
def number(chs):
    k = 0; idx = {}
    for c in chs:
        for a in c['arts']:
            k += 1; a['no'] = k
            assert a['t'] not in idx, a['t']; idx[a['t']] = k
    return idx
def serial(chs):
    return ''.join('<h4 class="ch">第%s章　%s</h4>' % (cn(i + 1), c['name'])
                   + ''.join('<div class="art"><span class="t">第 %d 條　%s</span>%s</div>' % (a['no'], a['t'], a['b']) for a in c['arts'])
                   for i, c in enumerate(chs))

class Doc:
    def __init__(s, d, did):
        s.id = did; s.d = copy.deepcopy(d); s.chs = parse(d['h'])
    def a(s, title):
        for c in s.chs:
            for x in c['arts']:
                if x['t'] == title: return x
        raise KeyError(title)
    def rep(s, title, old, new, cnt=1):
        x = s.a(title); n = x['b'].count(old)
        assert n == cnt, (s.id, title, old[:40], n)
        x['b'] = x['b'].replace(old, new)
    def body(s, title, b, newtitle=None):
        x = s.a(title); x['b'] = b
        if newtitle: x['t'] = newtitle
    def after(s, title, nt, b):
        for c in s.chs:
            for i, x in enumerate(c['arts']):
                if x['t'] == title:
                    c['arts'].insert(i + 1, dict(no=0, t=nt, b=b)); return
        raise KeyError(title)
    def chapter_before(s, chname, name, arts):
        i = [c['name'] for c in s.chs].index(chname)
        s.chs.insert(i, dict(name=name, arts=[dict(no=0, t=t, b=b) for t, b in arts]))

