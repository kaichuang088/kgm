ZH = '〇一二三四五六七八九'
def cn(n):
    if n < 10: return ZH[n]
    if n < 20: return '十' + (ZH[n % 10] if n % 10 else '')
    return ZH[n // 10] + '十' + (ZH[n % 10] if n % 10 else '')

# ── 標記 ──
def P(t): return '<p>' + t + '</p>'
def OL(*items): return '<ol class="kuan">' + ''.join('<li><b>%s、</b>%s</li>' % (cn(i + 1), x) for i, x in enumerate(items)) + '</ol>'
def TBL(cap, head, rows, num=()):
    h = '<table class="t"><caption>%s</caption><thead><tr>%s</tr></thead><tbody>' % (cap, ''.join('<th>%s</th>' % x for x in head))
    for r in rows:
        h += '<tr>' + ''.join(('<td class="num">%s</td>' if j in num else '<td>%s</td>') % c for j, c in enumerate(r)) + '</tr>'
    return h + '</tbody></table>'
def NOTE(t): return '<div class="note">' + t + '</div>'

